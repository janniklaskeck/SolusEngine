	class SPhysicsWorld
	{
		friend class SPhysicsBody;

	public:

		SPhysicsWorld();

		~SPhysicsWorld();

		void Tick(float DeltaTime);

		STransform GetBodyTransform(const JPH::BodyID BodyId) const;

	public:

		void SetActive(const SRigidBodyComponent& Component, const bool bActive);

		const JPH::BodyID CreateBoxBody(SRigidBodyComponent& RigidBodyComponent);

		void QueueBodyCreation(SRigidBodyComponent& RigidBodyComponent);

		void QueueBodyDestruction(SRigidBodyComponent& RigidBodyComponent);

		void FlushQueues();

		void RemovePhysicsBody(const JPH::BodyID BodyId);

		void DestroyPhysicsBody(const JPH::BodyID BodyId);

	private:

		// This is the max amount of rigid bodies that you can add to the physics system. If you try to add more you'll get an error.
		// Note: This value is low because this is a simple test. For a real project use something in the order of 65536.
		const uint32 cMaxBodies = 65536;

		// This determines how many mutexes to allocate to protect rigid bodies from concurrent access. Set it to 0 for the default settings.
		const uint32 cNumBodyMutexes = 0;

		// This is the max amount of body pairs that can be queued at any time (the broad phase will detect overlapping
		// body pairs based on their bounding boxes and will insert them into a queue for the narrowphase). If you make this buffer
		// too small the queue will fill up and the broad phase jobs will start to do narrow phase work. This is slightly less efficient.
		// Note: This value is low because this is a simple test. For a real project use something in the order of 65536.
		const uint32 cMaxBodyPairs = 65536;

		// This is the maximum size of the contact constraint buffer. If more contacts (collisions between bodies) are detected than this
		// number then these contacts will be ignored and bodies will start interpenetrating / fall through the world.
		// Note: This value is low because this is a simple test. For a real project use something in the order of 10240.
		const uint32 cMaxContactConstraints = 10240;

		// We need a temp allocator for temporary allocations during the physics update. We're
		// pre-allocating 10 MB to avoid having to do allocations during the physics update.
		// B.t.w. 10 MB is way too much for this example but it is a typical value you can use.
		// If you don't want to pre-allocate you can also use TempAllocatorMalloc to fall back to
		// malloc / free.
		std::unique_ptr<JPH::TempAllocatorImpl> TempAllocator;

		// We need a job system that will execute physics jobs on multiple threads. Typically
		// you would implement the JobSystem interface yourself and let Jolt Physics run on top
		// of your own job scheduler. JobSystemThreadPool is an example implementation.
		JPH::JobSystemThreadPool JobSystem;

		// Create mapping table from object layer to broadphase layer
		// Note: As this is an interface, PhysicsSystem will take a reference to this so this instance needs to stay alive!
		// Also have a look at BroadPhaseLayerInterfaceTable or BroadPhaseLayerInterfaceMask for a simpler interface.
		BPLayerInterfaceImpl broad_phase_layer_interface;

		// Create class that filters object vs broadphase layers
		// Note: As this is an interface, PhysicsSystem will take a reference to this so this instance needs to stay alive!
		// Also have a look at ObjectVsBroadPhaseLayerFilterTable or ObjectVsBroadPhaseLayerFilterMask for a simpler interface.
		ObjectVsBroadPhaseLayerFilterImpl object_vs_broadphase_layer_filter;

		// Create class that filters object vs object layers
		// Note: As this is an interface, PhysicsSystem will take a reference to this so this instance needs to stay alive!
		// Also have a look at ObjectLayerPairFilterTable or ObjectLayerPairFilterMask for a simpler interface.
		ObjectLayerPairFilterImpl object_vs_object_layer_filter;

		JPH::PhysicsSystem PhysicsSystem;

		MyBodyActivationListener body_activation_listener;
		MyContactListener contact_listener;

		std::vector<JPH::BodyID> ActivatedConstructionQueue;
		std::vector<JPH::BodyID> DormantConstructionQueue;

		std::vector<JPH::BodyID> BodyDestructionQueue;
	};
